import json
import os
import re
from datetime import datetime

from langchain_core.messages import BaseMessage, SystemMessage, HumanMessage, get_buffer_string
from langgraph.graph.message import add_messages
from typing import Annotated, Sequence
from typing_extensions import TypedDict, Dict, List

from agents.base_agent import BaseAgent
from utils.tools import extract_json_from_message


class AgentState(TypedDict):
    messages: Annotated[Sequence[BaseMessage], add_messages]
    skills: List[Dict[str, str]]


# ----------------------------------------------------
# SKILL GENERATOR
# ----------------------------------------------------

def make_skill_gen_node(skill_agent: BaseAgent, data, cfg):
    """
    Creates the skill_gen node that proposes k skills per generation. The agent is also provided with a context
    of previous skills generated by itself to ensure no repetitive skills.
    :param skill_agent:
    :param data:
    :return:
    """
    def node(state: AgentState):
        prompt_vars = cfg.get("dataset", {})

        system_message = data["system"]  # str
        human_message = data["human"]  # str
        human_message = human_message.format(**prompt_vars)

        context = get_context(state)
        context_prompt = (
            "Here is the context containing skill names of previously generated skills. "
            "Ensure that you DO NOT repeat any of these skills and generate diverse new skills:\n"
            "{context}"
        )

        context_prompt = context_prompt.format(context=context)

        messages = [
            SystemMessage(content=system_message),
            HumanMessage(content=context_prompt),
            HumanMessage(content=human_message),
        ]

        output = skill_agent.generate(get_buffer_string(messages))  # output type: AIMessage

        raw_text = output.content.strip()

        try:
            new_skills = json.loads(raw_text)
        except:
            try:
                new_skills = json.loads(clean_json_text(raw_text))
            except json.JSONDecodeError as e:
                raise ValueError(
                    f"SkillGenerator returned invalid JSON:\n{raw_text}"
                ) from e

        updated_skills = state["skills"] + new_skills

        return {
            "messages": [output],
            "skills": updated_skills,
        }

    return node


def get_context(state: AgentState):
    try:
        skills = state["skills"]  # skills is a list of dict
        skill_names = [": ".join((skill["skill_name"], skill["skill_intent"])) for skill in skills if skill]

    except KeyError as e:
        print("============Exception occurred in loading context: ", e)
        skill_names = []

    return skill_names


def clean_json_text(text: str) -> str:
    # Remove opening ``` or ```json (or ```anything)
    text = re.sub(r"^```[\w-]*\s*", "", text.strip())
    # Remove closing ```
    text = re.sub(r"\s*```$", "", text)
    return text.strip()



"""
simulator/utils/robot_config.py

Loads the per-robot YAML spec — the single source of truth for a robot's
morphology, shared by the simulator and the LLM agent (agent/).

Expected YAML structure
-----------------------
name: humanoid
scene_xml: assets/scenes/flat.xml
mjcf: assets/unitree_go2w/go2w.xml
base_body: base_link
sim_freq: 200
end_effectors:                       # ordered; names are what gait code uses
  - {name: FL, body: FL_calf, site: FL_foot, ground_offset: 0.104}
  - ...
joints:                              # in model qpos[7:] order
  - {name: FL_hip_joint, limits: [-1.0472, 1.0472]}
  - {name: FL_foot_joint, passive: true}
  - ...
base_height_range: [0.10, 0.68]
camera: {lookat: [0.0, 0.0, 0.35], distance: 2.5, azimuth: 90, elevation: -20}
example_skill: robots/examples/unitree_go2w.py
robot_card: |
  Free-text morphology description injected into the agent prompts.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Tuple
import yaml


@dataclass
class RobotSpec:
    name: str
    scene_xml: str
    mjcf: str
    base_body: str
    sim_freq: int
    end_effectors: List[Dict]      # [{name, body, site, ground_offset}, ...]
    joints: List[Dict]             # [{name, limits, passive}, ...] in qpos[7:] order
    base_height_range: Tuple[float, float]
    camera: Dict = field(default_factory=dict)
    example_skill: str = ""
    robot_card: str = ""
    null_space_gain: float = 0.1   # IK rest-pose pull; lower = further EE reach
    # Morphology class (informational; this repo ships the humanoid only). (a quadruped
    # is FLAT-terrain-only, body-frame feet, velocity base, always-contact grounding,
    # no floating; a humanoid gets the general world-frame / grounding-off machinery).
    # "generic" = no branching (the shared prompts + current policy).
    kind: str = "generic"          # {"quadruped", "humanoid", "generic"}
    environments: List[Dict] = field(default_factory=list)  # named scenes the skill may run in
    exemplars: List[Dict] = field(default_factory=list)     # curated hand-authored reference skills
    # Extra body parts (beyond the IK end-effectors) that a skill MAY declare as
    # ground/surface contacts — e.g. knees/shins for a hands-and-knees crawl, a
    # forearm, a hip. They are NOT IK targets; the framework grounds to them and
    # the contact checks include them, so ANY body can bear weight on a surface.
    # [{name, body, ground_offset}]. Non-penetration already applies to ALL geoms.
    contact_bodies: List[Dict] = field(default_factory=list)
    # Named reference STANCES a skill may start from / transition into — the home
    # 4-leg quadruped stance plus rearing poses (stand on 2 legs, torso pitched/rolled
    # ~90°). Each: {name, description, stance_ees:[...], base_rpy:[r,p,y], base_height,
    # joints:{name:rad}}. Prompt DATA only (injected via {home_poses}); the skill drives
    # the base orientation + free-leg joints + stance contacts through the EXISTING base
    # class — no runtime reader, no new control path. Generated by gen_home_poses.py.
    home_poses: List[Dict] = field(default_factory=list)
    # Per-joint physical velocity/accel ceilings {"vel": {joint: rad/s}, "accel":
    # {joint: rad/s²}}, generated by gen_robot_summary into robots/<name>/dynamics.json
    # (order-of-magnitude, from torque/inertia). Empty when the MJCF carries no
    # torque source — the joint_velocity_envelope check then self-skips.
    joint_dynamics: Dict = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Derived: end-effectors
    # ------------------------------------------------------------------
    @property
    def ee_names(self) -> List[str]:
        return [ee["name"] for ee in self.end_effectors]

    @property
    def ee_bodies(self) -> List[str]:
        return [ee["body"] for ee in self.end_effectors]

    @property
    def ee_sites(self) -> List[str]:
        return [ee.get("site", ee["body"]) for ee in self.end_effectors]

    @property
    def ee_ground_offsets(self) -> List[float]:
        return [float(ee.get("ground_offset", 0.0)) for ee in self.end_effectors]

    @property
    def ee_contact(self) -> List[bool]:
        """Per-EE: is it a ground contact? (default True). Non-contact EEs
        (e.g. a humanoid's hands) are IK targets but excluded from the
        ground-penetration and airtime checks."""
        return [bool(ee.get("contact", True)) for ee in self.end_effectors]

    @property
    def contact_ee_indices(self) -> List[int]:
        return [i for i, c in enumerate(self.ee_contact) if c]

    @property
    def wheel_ee_indices(self) -> List[int]:
        """EEs that are wheels — allowed to roll (skate) while in contact."""
        return [i for i, ee in enumerate(self.end_effectors) if ee.get("wheel", False)]

    # ------------------------------------------------------------------
    # Derived: extra (non-EE) declarable contact bodies (knees, shins, ...)
    # ------------------------------------------------------------------
    @property
    def joint_speed_ceilings(self) -> Dict[str, float]:
        """Per-joint peak velocity ceilings (rad/s); empty if no dynamics data."""
        return dict(self.joint_dynamics.get("vel", {}) or {})

    @property
    def joint_accel_ceilings(self) -> Dict[str, float]:
        """Per-joint acceleration ceilings (rad/s²); empty if no dynamics data."""
        return dict(self.joint_dynamics.get("accel", {}) or {})

    @property
    def jump_height(self):
        """Estimated ballistic apex RISE (m) from a leg push, or None (no torque tier)."""
        return (self.joint_dynamics.get("jump") or {}).get("height")

    @property
    def jump_flight_time(self):
        """Estimated jump airtime (s), or None (no torque tier)."""
        return (self.joint_dynamics.get("jump") or {}).get("flight_time")

    @property
    def contact_body_names(self) -> List[str]:
        return [c["name"] for c in self.contact_bodies]

    @property
    def contact_body_bodies(self) -> List[str]:
        return [c["body"] for c in self.contact_bodies]

    @property
    def contact_body_offsets(self) -> List[float]:
        return [float(c.get("ground_offset", 0.0)) for c in self.contact_bodies]

    @property
    def contact_body_sites(self) -> List[str]:
        """IK site per contact body (falls back to the body name -> body-center
        target). A contact body with a `<site>` gets a precise contact-point IK
        target; without one, IK aims at the body origin (the ground_offset carries
        the vertical)."""
        return [c.get("site", c["body"]) for c in self.contact_bodies]

    # ------------------------------------------------------------------
    # Derived: the UNION IK roster (end-effectors + extra contact bodies).
    # The controller builds ONE IK over this union, so ANY declared contact body
    # can be given a world target and PLACED by IK like a foot (not just FK-seated).
    # ------------------------------------------------------------------
    @property
    def ik_names(self) -> List[str]:
        return list(self.ee_names) + list(self.contact_body_names)

    @property
    def ik_bodies(self) -> List[str]:
        return list(self.ee_bodies) + list(self.contact_body_bodies)

    @property
    def ik_sites(self) -> List[str]:
        return list(self.ee_sites) + list(self.contact_body_sites)

    # ------------------------------------------------------------------
    # Derived: joints
    # ------------------------------------------------------------------
    @property
    def joint_names(self) -> List[str]:
        """All joint names, in model qpos[7:] order (what gets recorded)."""
        return [j["name"] for j in self.joints]

    @property
    def actuated_joint_names(self) -> List[str]:
        return [j["name"] for j in self.joints if not j.get("passive", False)]

    @property
    def passive_joint_indices(self) -> List[int]:
        """Indices into the recorded joint vector that are unactuated."""
        return [i for i, j in enumerate(self.joints) if j.get("passive", False)]

    @property
    def joint_limits(self) -> Dict[str, Tuple[float, float]]:
        """Actuated joints only, in order: name -> (lo, hi)."""
        return {
            j["name"]: tuple(j["limits"])
            for j in self.joints
            if not j.get("passive", False)
        }

    # ------------------------------------------------------------------
    # Derived: environments (named scenes a skill may run in)
    # ------------------------------------------------------------------
    @property
    def all_environments(self) -> List[Dict]:
        """Named environments, always including an implicit 'flat' default (the
        robot's own scene_xml, contact grounding, no objects) as the first entry."""
        flat = dict(name="flat", scene=self.scene_xml, grounding="contact",
                    objects=[], description="Flat floor. Default for locomotion and "
                    "in-place skills — no objects, no obstacles.")
        rest = [e for e in self.environments if e.get("name") != "flat"]
        return [flat] + rest

    def get_environment(self, name: str) -> Dict:
        """Resolve an environment by name; unknown/empty -> the flat default.

        A MISSING environment is marked `missing: True` rather than silently
        substituted. Falling back to a bare floor is the dangerous case: the skill's
        object code then animates a body that does not exist, every object check
        SELF-SKIPS (no objects in the scene), and the run can score as a clean PASS
        while doing nothing it was asked to do. Callers surface the flag; the run
        still proceeds so the failure is diagnosable rather than fatal.
        """
        if name:
            for e in self.all_environments:
                if e.get("name") == name:
                    return e
            print(f"⚠️  MISSING ASSET: environment '{name}' is not registered for "
                  f"robot '{self.name}'. Create assets/scenes/{name}.xml (floor + the "
                  f"object) and add it under `environments:` in "
                  f"robots/{self.name}/robot.yaml. Falling back to 'flat' (no objects) "
                  f"— any object this skill expects will NOT exist.")
            fallback = dict(self.all_environments[0])
            fallback["missing"] = True
            fallback["requested"] = name
            return fallback
        return self.all_environments[0]

    def get_exemplar(self, name: str) -> Dict:
        """Curated reference skill by name (or None). `file` defaults to
        robots/<robot>/exemplars/<name>.py."""
        for ex in self.exemplars:
            if ex.get("name") == name:
                return ex
        return None


# ---------------------------------------------------------------------------
# YAML loader
# ---------------------------------------------------------------------------
_REQUIRED_KEYS = [
    "name", "scene_xml", "base_body", "end_effectors", "joints",
    "base_height_range",
]


def load_robot_spec(robot_name: str, robots_dir: str = "robots") -> RobotSpec:
    """Load a robot spec from <robots_dir>/<robot_name>/robot.yaml"""
    path = Path(robots_dir) / robot_name / "robot.yaml"
    if not path.exists():
        available = sorted(
            p.parent.name for p in Path(robots_dir).glob("*/robot.yaml")
        )
        raise FileNotFoundError(
            f"Robot config not found: {path}\n"
            f"Available robots: {available}"
        )

    with open(path) as f:
        data = yaml.safe_load(f)

    # Optional generated sidecar with per-joint velocity/accel ceilings.
    joint_dynamics = {}
    dyn_path = path.parent / "dynamics.json"
    if dyn_path.exists():
        try:
            import json
            with open(dyn_path) as jf:
                joint_dynamics = json.load(jf) or {}
        except Exception:
            joint_dynamics = {}

    missing = [k for k in _REQUIRED_KEYS if k not in data]
    if missing:
        raise ValueError(f"Robot config {path} missing required keys: {missing}")

    for j in data["joints"]:
        if not j.get("passive", False) and "limits" not in j:
            raise ValueError(
                f"Robot config {path}: joint '{j.get('name')}' needs 'limits' "
                f"(or 'passive: true')"
            )

    return RobotSpec(
        name=data["name"],
        scene_xml=data["scene_xml"],
        mjcf=data.get("mjcf", ""),
        base_body=data["base_body"],
        sim_freq=int(data.get("sim_freq", 200)),
        end_effectors=data["end_effectors"],
        joints=data["joints"],
        base_height_range=tuple(data["base_height_range"]),
        camera=data.get("camera", {}),
        example_skill=data.get("example_skill", ""),
        robot_card=data.get("robot_card", ""),
        null_space_gain=float(data.get("null_space_gain", 0.1)),
        kind=str(data.get("kind", "generic")),
        environments=data.get("environments", []),
        exemplars=data.get("exemplars", []),
        contact_bodies=data.get("contact_bodies", []),
        home_poses=data.get("home_poses", []),
        joint_dynamics=joint_dynamics,
    )
